/**
 * Generates lightweight content data files from the lesson MDX sources:
 *   - content/lesson-index.ts  → searchable lesson metadata (no MDX imports,
 *     safe to bundle into client components like the ⌘K palette)
 *   - content/flashcards.ts     → every <Term> extracted as a flashcard
 *
 * Run after adding/editing lessons:  node scripts/generate-content-data.mjs
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const LESSONS_DIR = join(ROOT, "content", "lessons");

const CHAPTER_ORDER = [
  "preparation",
  "design",
  "fieldwork",
  "reporting",
  "dissemination",
];

function listChapters() {
  return readdirSync(LESSONS_DIR).filter((d) =>
    statSync(join(LESSONS_DIR, d)).isDirectory(),
  );
}

const TERM_RE = /<Term\s+name="([^"]+)">([\s\S]*?)<\/Term>/g;

function cleanText(s) {
  return s
    .replace(/\s+/g, " ")
    .replace(/\\"/g, '"')
    .trim();
}

const lessons = [];
const flashcards = [];

for (const chapter of listChapters()) {
  const dir = join(LESSONS_DIR, chapter);
  const files = readdirSync(dir).filter((f) => f.endsWith(".mdx"));
  for (const file of files) {
    const slug = file.replace(/\.mdx$/, "");
    const raw = readFileSync(join(dir, file), "utf8");
    const { data, content } = matter(raw);

    lessons.push({
      chapter,
      slug,
      href: `/learn/${chapter}/${slug}`,
      title: data.title ?? slug,
      lede: data.lede ?? "",
      section: data.handbookSection ?? "",
      minutes: data.estimatedMinutes ?? 0,
      order: data.order ?? 0,
    });

    let m;
    TERM_RE.lastIndex = 0;
    while ((m = TERM_RE.exec(content)) !== null) {
      const term = cleanText(m[1]);
      const definition = cleanText(m[2]);
      if (term && definition) {
        flashcards.push({
          chapter,
          lessonSlug: slug,
          lessonTitle: data.title ?? slug,
          term,
          definition,
        });
      }
    }
  }
}

// Stable sort: by chapter order, then lesson order
const chapIdx = (c) => {
  const i = CHAPTER_ORDER.indexOf(c);
  return i < 0 ? 999 : i;
};
lessons.sort((a, b) => chapIdx(a.chapter) - chapIdx(b.chapter) || a.order - b.order);

const banner = `/**\n * AUTO-GENERATED by scripts/generate-content-data.mjs\n * Do not edit by hand — re-run the script after changing lessons.\n */\n`;

writeFileSync(
  join(ROOT, "content", "lesson-index.ts"),
  banner +
    `export type LessonIndexEntry = {\n` +
    `  chapter: string;\n  slug: string;\n  href: string;\n  title: string;\n  lede: string;\n  section: string;\n  minutes: number;\n  order: number;\n};\n\n` +
    `export const LESSON_SEARCH_INDEX: LessonIndexEntry[] = ${JSON.stringify(
      lessons,
      null,
      2,
    )};\n`,
  "utf8",
);

writeFileSync(
  join(ROOT, "content", "flashcards.ts"),
  banner +
    `export type Flashcard = {\n` +
    `  chapter: string;\n  lessonSlug: string;\n  lessonTitle: string;\n  term: string;\n  definition: string;\n};\n\n` +
    `export const FLASHCARDS: Flashcard[] = ${JSON.stringify(
      flashcards,
      null,
      2,
    )};\n`,
  "utf8",
);

console.log(
  `Generated content/lesson-index.ts (${lessons.length} lessons) and content/flashcards.ts (${flashcards.length} cards).`,
);
