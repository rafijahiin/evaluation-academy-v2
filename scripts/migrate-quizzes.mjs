#!/usr/bin/env node
/**
 * Extract STAGE_QUIZ and FINAL_EXAM from v1 content.js and emit a
 * typed TypeScript module at content/quizzes.ts with chapter tags
 * applied so chapter quizzes can pick the relevant questions.
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, "..");

const V1_CONTENT_PATH = "C:/Users/HP/.claude/projects/evaluation-academy/content.js";

async function loadArray(varName) {
  const raw = await fs.readFile(V1_CONTENT_PATH, "utf-8");
  const re = new RegExp(`window\\.${varName}\\s*=\\s*(\\[[\\s\\S]*?\\n\\]);`);
  const m = raw.match(re);
  if (!m) throw new Error(`Could not find ${varName}`);
  return new Function(`return (${m[1]});`)();
}

/**
 * Chapter tags for the final exam (questions ordered as they appear in v1).
 * Q1: Exemplaria launch scenario           → preparation
 * Q2: ToC arrange (skipped from MCQ flow)  → cross
 * Q3: 5 OECD-DAC criteria                  → design
 * Q4: humanitarian +2 criteria             → design
 * Q5: YEE recruitment timing               → preparation
 * Q6: CPE Manager identity                 → preparation
 * Q7: Annex stakeholder map                → preparation
 * Q8: Evaluation matrix timing             → design
 * Q9: Theory-based contribution            → design
 * Q10: 11-month minimum                    → preparation
 * Q11: analytical chain                    → reporting
 * Q12: recommendations protocol            → reporting
 * Q13: 3 transformative results            → cross
 * Q14: ERG 4 moments                       → preparation
 * Q15: EQA                                 → cross
 * Q16: no-UNFPA-staff-at-data-collection   → fieldwork
 * Q17: 4 management response positions     → dissemination
 */
const FINAL_EXAM_CHAPTERS = [
  "preparation", // Q1 scenario
  "cross",       // Q2 arrange
  "design",      // Q3
  "design",      // Q4
  "preparation", // Q5
  "preparation", // Q6
  "preparation", // Q7
  "design",      // Q8
  "design",      // Q9
  "preparation", // Q10
  "reporting",   // Q11
  "reporting",   // Q12
  "cross",       // Q13
  "preparation", // Q14
  "cross",       // Q15
  "fieldwork",   // Q16
  "dissemination", // Q17
];

/**
 * Stage quiz: broad introductory questions. Tag each so they can also feed
 * the chapter quizzes.
 */
const STAGE_QUIZ_CHAPTERS = [
  "cross",       // Handbook is for CPEs
  "preparation", // YEE recruited at stage 1
  "design",      // 5 OECD-DAC criteria
  "design",      // Why impact excluded
  "design",      // Theory-based contribution
  "preparation", // ERG 4 moments
  "reporting",   // Co-creation recommendations
  "cross",       // 3 transformative results
  "design",      // Design report v1 v2
  "preparation", // CPE Manager
];

function normalize(q, chapter, source) {
  // type detection
  if (q.type === "arrange") {
    return {
      id: `${source}-${q.q.slice(0, 24).replace(/\W+/g, "-").toLowerCase()}`,
      type: "arrange",
      chapter,
      source,
      question: q.q,
      scenarioTitle: q.scenarioTitle,
      scenarioBody: q.scenarioBody,
      items: q.items,
      weight: q.weight ?? 1,
    };
  }
  return {
    id: `${source}-${q.q.slice(0, 24).replace(/\W+/g, "-").toLowerCase()}`,
    type: q.type === "scenario" ? "scenario" : "mcq",
    chapter,
    source,
    question: q.q,
    scenarioTitle: q.scenarioTitle,
    scenarioBody: q.scenarioBody,
    options: q.options,
    correct: q.correct,
    weight: q.weight ?? 1,
  };
}

async function main() {
  const stage = await loadArray("STAGE_QUIZ");
  const exam = await loadArray("FINAL_EXAM");

  const stageNorm = stage.map((q, i) =>
    normalize(q, STAGE_QUIZ_CHAPTERS[i] ?? "cross", "stage"),
  );
  const examNorm = exam.map((q, i) =>
    normalize(q, FINAL_EXAM_CHAPTERS[i] ?? "cross", "exam"),
  );

  // Build chapter pools — stage questions + final-exam questions tagged that chapter
  const chapters = ["preparation", "design", "fieldwork", "reporting", "dissemination"];
  const chapterPools = {};
  for (const c of chapters) {
    chapterPools[c] = [
      ...stageNorm.filter((q) => q.chapter === c),
      ...examNorm.filter((q) => q.chapter === c && q.type !== "arrange"),
    ];
  }

  const out = [];
  out.push("/**");
  out.push(" * AUTO-GENERATED by scripts/migrate-quizzes.mjs");
  out.push(" * Quiz + exam question data sourced from v1 content.js.");
  out.push(" */");
  out.push("");
  out.push("export type ArrangeItem = { text: string; level: number; chip: string };");
  out.push("");
  out.push("export type Question = {");
  out.push("  id: string;");
  out.push('  type: "mcq" | "scenario" | "arrange";');
  out.push("  chapter: string;");
  out.push('  source: "stage" | "exam";');
  out.push("  question: string;");
  out.push("  scenarioTitle?: string;");
  out.push("  scenarioBody?: string;");
  out.push("  options?: string[];");
  out.push("  correct?: number;");
  out.push("  items?: ArrangeItem[];");
  out.push("  weight: number;");
  out.push("};");
  out.push("");
  out.push("export const STAGE_QUIZ: Question[] = " + JSON.stringify(stageNorm, null, 2) + ";");
  out.push("");
  out.push("export const FINAL_EXAM: Question[] = " + JSON.stringify(examNorm, null, 2) + ";");
  out.push("");
  out.push("export const CHAPTER_QUIZZES: Record<string, Question[]> = " +
    JSON.stringify(chapterPools, null, 2) + ";");
  out.push("");
  out.push("export const PASS_THRESHOLD = 0.8; // 80% required for certificate");

  await fs.writeFile(path.join(ROOT, "content", "quizzes.ts"), out.join("\n"), "utf-8");

  const total = stageNorm.length + examNorm.length;
  console.log(`✓ Wrote content/quizzes.ts — ${stageNorm.length} stage + ${examNorm.length} exam (= ${total} questions)`);
  console.log(`  Chapter pools:`);
  for (const c of chapters) {
    console.log(`    ${c}: ${chapterPools[c].length} questions`);
  }
}

main().catch((e) => { console.error(e); process.exit(1); });
