#!/usr/bin/env node
/**
 * Scan content/lessons/<chapter>/<NN>-<slug>.mdx and emit:
 *   content/lessons-manifest.ts  — typed registry of all lessons with
 *   frontmatter, used by /learn/[chapter] index pages, the lesson reader
 *   (prev/next nav, breadcrumb), and the dashboard (progress per chapter).
 *
 * Run: node scripts/generate-manifest.mjs
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, "..");
const LESSONS_DIR = path.join(ROOT, "content", "lessons");
const OUT_FILE = path.join(ROOT, "content", "lessons-manifest.ts");

async function main() {
  const chapters = (await fs.readdir(LESSONS_DIR, { withFileTypes: true }))
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();

  const entries = []; // { chapter, slug, frontmatter, varName }
  for (const chapter of chapters) {
    const files = (await fs.readdir(path.join(LESSONS_DIR, chapter)))
      .filter((f) => f.endsWith(".mdx"))
      .sort();
    for (const file of files) {
      const slug = file.replace(/\.mdx$/, "");
      const full = path.join(LESSONS_DIR, chapter, file);
      const raw = await fs.readFile(full, "utf-8");
      const { data } = matter(raw);
      const varName = `${chapter}_${slug.replace(/[^a-zA-Z0-9]/g, "_")}`;
      entries.push({ chapter, slug, frontmatter: data, varName });
    }
  }

  const lines = [];
  lines.push(`/**`);
  lines.push(` * AUTO-GENERATED by scripts/generate-manifest.mjs`);
  lines.push(` * Do not edit by hand — re-run after adding/removing lessons.`);
  lines.push(` */`);
  lines.push(`import type { ComponentType } from "react";`);
  lines.push("");
  // imports
  for (const e of entries) {
    lines.push(
      `import ${e.varName} from "./lessons/${e.chapter}/${e.slug}.mdx";`,
    );
  }
  lines.push("");

  lines.push(`export type LessonFrontmatter = {`);
  lines.push(`  title: string;`);
  lines.push(`  order: number;`);
  lines.push(`  originalTitle?: string;`);
  lines.push(`  lede?: string;`);
  lines.push(`  estimatedMinutes: number;`);
  lines.push(`  handbookSection?: string;`);
  lines.push(`  handbookPages?: string;`);
  lines.push(`  unegRefs?: string[];`);
  lines.push(`};`);
  lines.push("");

  lines.push(`export type LessonEntry = {`);
  lines.push(`  chapter: string;`);
  lines.push(`  slug: string;`);
  lines.push(`  href: string;`);
  lines.push(`  frontmatter: LessonFrontmatter;`);
  lines.push(`  Component: ComponentType;`);
  lines.push(`};`);
  lines.push("");

  lines.push(`export const LESSONS: LessonEntry[] = [`);
  for (const e of entries) {
    const fmJson = JSON.stringify(e.frontmatter, null, 2)
      .split("\n")
      .map((l) => `    ${l}`)
      .join("\n");
    lines.push(`  {`);
    lines.push(`    chapter: ${JSON.stringify(e.chapter)},`);
    lines.push(`    slug: ${JSON.stringify(e.slug)},`);
    lines.push(`    href: ${JSON.stringify(`/learn/${e.chapter}/${e.slug}`)},`);
    lines.push(`    frontmatter: ${fmJson.trim()},`);
    lines.push(`    Component: ${e.varName},`);
    lines.push(`  },`);
  }
  lines.push(`];`);
  lines.push("");

  lines.push(`// Indexed lookup`);
  lines.push(
    `export const LESSON_INDEX: Record<string, LessonEntry> = Object.fromEntries(`,
  );
  lines.push(`  LESSONS.map((l) => [\`\${l.chapter}/\${l.slug}\`, l]),`);
  lines.push(`);`);
  lines.push("");

  lines.push(`export function getLessonsByChapter(chapter: string): LessonEntry[] {`);
  lines.push(`  return LESSONS.filter((l) => l.chapter === chapter)`);
  lines.push(`    .sort((a, b) => a.frontmatter.order - b.frontmatter.order);`);
  lines.push(`}`);

  await fs.writeFile(OUT_FILE, lines.join("\n") + "\n", "utf-8");
  console.log(`✓ Wrote manifest with ${entries.length} lessons →`, path.relative(ROOT, OUT_FILE));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
